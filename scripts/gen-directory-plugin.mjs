// --- resolver fence -> prose -------------------------------------------------

export function resolverProse(fenceLines, indent) {
  const body = fenceLines.join("\n");
  const call = fenceLines.find((l) => l.includes("resolve-space.sh"));
  if (!call) throw new GenError("resolver fence without a resolve-space.sh call");
  const field = (n) => {
    const m = body.match(new RegExp(`^\\s*([a-z_]+)="\\$\\(printf '%s\\\\n' "\\$resolved" \\| cut -f${n}\\)"`, "m"));
    return m ? m[1] : null;
  };
  const spaceVar = field("1");
  const sourceVar = field("2");
  const restVar = field("3-");
  if (!spaceVar) throw new GenError(`resolver fence does not read the Space: ${call.trim()}`);
  const newRepo = call.includes("--new-repo-fallback");

  let argStep = null;
  if (call.includes("--arg ")) {
    argStep = "A Space name the user passed after the command (`arg`).";
  } else {
    const m = call.match(/--args "([^"]*)"/);
    if (!m) throw new GenError(`resolver fence passes no arguments: ${call.trim()}`);
    if (m[1] !== "") {
      const raw = body.match(/^\s*raw_args="<(.+)>"$/m);
      const what = raw ? raw[1].replace(/\/wenlan-([a-z]+)/g, "/wenlan:$1") : "the arguments the user typed";
      argStep = `A \`space:<name>\` token in ${what} (\`arg\`).`;
    }
  }

  const steps = [
    "The `WENLAN_SPACE` environment variable, when set (`locked-env`).",
    ...(argStep ? [argStep] : []),
    "The `WENLAN_DEFAULT_SPACE` environment variable, when set (`default-env`).",
    "In `~/.wenlan/spaces.toml`, the `[[mapping]]` entry whose `prefix` is the current folder or contains it, the longest one when several do; use its `space` (`cwd-config`).",
    "Inside a Git repository: the main repository's folder name, when `wenlan spaces show <name> --format json` succeeds (`cwd-repo`)." +
      (newRepo ? " When that command fails, still use the folder name (`cwd-repo-new`)." : ""),
    "Otherwise none: leave it empty (`unscoped`).",
  ];
  const keep = [`\`${spaceVar}\` is the name`];
  if (sourceVar) keep.push(`\`${sourceVar}\` is the label in brackets`);
  if (restVar) keep.push(`\`${restVar}\` is the arguments with any \`space:<name>\` token removed`);
  const lines = [
    "Work out the Space in this order, using your own file and shell tools, and",
    "stop at the first step that gives a name:",
    "",
    ...steps.flatMap((s, i) => wrap(`${i + 1}. ${s}`, 80 - indent.length, "   ")),
    "",
    ...wrap(`Then ${keep.length > 1 ? `${keep.slice(0, -1).join(", ")} and ${keep.at(-1)}` : keep[0]}.`, 80 - indent.length, ""),
  ];
  // Lines the fence runs besides the resolver stay as a smaller fence.
  const known = /^\s*(raw_args|handoff_arg)="<.*>"$|resolve-space\.sh|^\s*[a-z_]+="\$\(printf '%s\\n' "\$resolved" \| cut -f[0-9-]+\)"$/;
  const rest = fenceLines.filter((l) => l.trim() && !known.test(l));
  if (rest.length) lines.push("", "```bash", ...rest.map((l) => l.slice(indent.length)), "```");
  return lines.map((l) => (l ? indent + l : l));
}

function wrap(text, width, hang) {
  const out = [];
  let line = "";
  // Keep each inline code span on one line.
  for (const word of text.match(/(?:`[^`]*`|[^ `])+/g) ?? []) {
    const next = line ? `${line} ${word}` : word;
    if (next.length > width && line) {
      out.push(line);
      line = hang + word;
    } else line = next;
  }
  if (line) out.push(line);
  return out;
}

export function swapResolverFences(path, text) {
  const lines = text.split("\n");
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const open = lines[i].match(/^(\s*)```bash\s*$/);
    if (open) {
      const end = lines.findIndex((l, j) => j > i && l.trim() === "```");
      if (end < 0) throw new GenError(`${path}: unterminated code fence at line ${i + 1}`);
      const fence = lines.slice(i + 1, end);
      if (fence.some((l) => l.includes("resolve-space.sh"))) {
        out.push(...resolverProse(fence, open[1]));
        i = end;
        continue;
      }
    }
    out.push(lines[i]);
  }
  return out.join("\n");
}

// --- other rewrites ----------------------------------------------------------

export function applyReplaceRuns(path, text, rules) {
  let lines = text.split("\n");
  for (const rule of rules.filter((r) => r.file === path)) {
    const hits = [];
    for (let i = 0; i + rule.from.length <= lines.length; i++) {
      if (rule.from.every((l, k) => lines[i + k] === l)) hits.push(i);
    }
    if (hits.length !== 1) throw new GenError(`${path}: replace run must match exactly once, matched ${hits.length}: ${rule.from[0]}`);
    lines = [...lines.slice(0, hits[0]), ...rule.to, ...lines.slice(hits[0] + rule.from.length)];
  }
  return lines.join("\n");
}

function renameFrontmatter(path, text) {
  if (!path.endsWith("/SKILL.md")) return text;
  const skill = skillOf(path);
  return text.replace(/^name: .*$/m, `name: ${skill}`);
}

export function transformFile(path, agentText) {
  let text = renameFrontmatter(path, agentText);
  text = swapResolverFences(path, text);
  text = applyReplaceRuns(path, text, REPLACE);
  text = text.replace(/\/wenlan-(brief|capture|recall|handoff)\b/g, "/wenlan:$1");
  for (const token of LEFTOVER_TOKENS) {
    if (text.includes(token)) throw new GenError(`${path}: leftover \`${token}\``);
  }
  return text;
}

// --- manifest, readme --------------------------------------------------------

function manifest(root) {
  const claude = JSON.parse(readFileSync(resolve(root, CLAUDE_MANIFEST), "utf8"));
  const out = {
    name: claude.name,
    displayName: claude.displayName,
    description: `${claude.description} Needs the free Wenlan app on this computer.`,
    author: claude.author,
    homepage: claude.homepage,
    repository: claude.repository,
    license: claude.license,
    keywords: claude.keywords,
  };
  return `${JSON.stringify(out, null, 2)}\n`;
}

