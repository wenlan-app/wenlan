// Generates plugin-directory/, the text-only edition of the Claude plugin that
// is submitted to the Claude plugin directory. The directory rejects, for an
// organization that is not Verified: command hooks, a bundled local MCP server,
// skills whose allowed-tools go beyond Read/Grep/Glob/LS, and any file that is
// not Markdown, text, JSON, YAML or a PNG/JPEG/GIF/WebP/ICO image (or that
// starts with `#!`). The regular plugin (plugin/) needs all of those, so this
// edition is built from the host-neutral Agent Skills set instead, which
// already has none of them except the Space resolver script.
//
// Source: the in-memory output of scripts/gen-agent-skills.mjs (so it follows
// the hand-written Claude skills, never a stale plugin-agents/ checkout).
//
// Per file:
//   1. path            : wenlan-<skill>/... -> <skill>/... (wenlan/ stays)
//   2. frontmatter     : name: wenlan-<skill> -> name: <skill>
//   3. resolver fence  : the ```bash block that calls resolve-space.sh becomes
//                        prose with the same resolution order, so no script ships
//   4. REPLACE         : exact contiguous line runs (below) -> final text
//   5. commands        : /wenlan-<skill> -> /wenlan:<skill>
//   6. guard           : leftover tokens, and the directory file rules on the
//                        whole plugin-directory/ tree
//
// The resolver script itself is dropped. The MCP server is not bundled: the
// Wenlan app (or `wenlan connect claude-code`) adds it to Claude Code, and the
// setup workflow says so when the round-trip fails.
//
// `--check` exits 1 when a generated file differs, a file under
// plugin-directory/ is generated by nothing, or the tree breaks a directory
// rule; `--root <dir>` points at another tree.
