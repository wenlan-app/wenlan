// --- tree --------------------------------------------------------------------

export function generateAll(root) {
  const agentOutputs = generateAgentSkills(root).filter((o) => o.path.startsWith(AGENT_SKILLS_PREFIX));
  const files = [];
  for (const o of agentOutputs) {
    const rel = o.path.slice(AGENT_SKILLS_PREFIX.length);
    if (rel.endsWith(".sh")) continue;
    const path = dirPath(rel);
    files.push({ path: `${OUT_ROOT}/skills/${path}`, text: transformFile(path, o.text) });
  }
  files.push({ path: `${OUT_ROOT}/.claude-plugin/plugin.json`, text: manifest(root) });
  files.push({ path: `${OUT_ROOT}/README.md`, text: README });
  files.push({ path: `${OUT_ROOT}/${ICON_OUT}`, bytes: readFileSync(resolve(root, ICON_SOURCE)) });
  return files;
}

// The directory's own rules, checked on what is actually on disk.
export function directoryViolations(root) {
  const base = resolve(root, OUT_ROOT);
  if (!existsSync(base)) return [];
  const out = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = resolve(d, e.name);
      const rel = relative(root, p).split("\\").join("/");
      if (e.isSymbolicLink()) out.push(`${rel}: symbolic links are not allowed`);
      else if (e.isDirectory()) walk(p);
      else {
        const ext = e.name.includes(".") ? e.name.slice(e.name.lastIndexOf(".")).toLowerCase() : "";
        if (!ALLOWED_EXTENSIONS.includes(ext)) out.push(`${rel}: file type not allowed`);
        const buf = readFileSync(p);
        if (buf[0] === 0x23 && buf[1] === 0x21) out.push(`${rel}: starts with #!`);
        if (e.name === ".mcp.json" || e.name === "hooks.json") out.push(`${rel}: hooks and MCP config are not allowed`);
        if (e.name === "SKILL.md") {
          const fm = buf.toString("utf8").split("\n---")[0];
          const m = fm.match(/^allowed-tools:(.*)$/m);
          if (m) {
            const tools = m[1].replace(/[[\]"']/g, "").split(/[ ,]+/).filter(Boolean);
            const bad = tools.filter((t) => !ALLOWED_TOOLS.includes(t));
            if (bad.length || !tools.length) out.push(`${rel}: allowed-tools beyond ${ALLOWED_TOOLS.join("/")}`);
          }
        }
        if (e.name === "plugin.json") {
          const j = JSON.parse(buf.toString("utf8"));
          for (const k of ["hooks", "mcpServers", "lspServers"]) if (k in j) out.push(`${rel}: \`${k}\` is not allowed`);
        }
      }
    }
  };
  walk(base);
  return out;
}

function stray(root, outputs) {
  const base = resolve(root, OUT_ROOT);
  if (!existsSync(base)) return [];
  const claimed = new Set(outputs.map((o) => o.path));
  const out = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = resolve(d, e.name);
      if (e.isDirectory()) walk(p);
      else {
        const rel = relative(root, p).split("\\").join("/");
        if (!claimed.has(rel)) out.push(rel);
      }
    }
  };
  walk(base);
  return out;
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const rootIdx = args.indexOf("--root");
  if (rootIdx >= 0 && !args[rootIdx + 1]) {
    console.error("usage: gen-directory-plugin.mjs [--check] [--root <dir>]");
    process.exit(2);
  }
  const root = rootIdx >= 0 ? resolve(args[rootIdx + 1]) : resolve(dirname(fileURLToPath(import.meta.url)), "..");

  let outputs;
  try {
    outputs = generateAll(root);
  } catch (err) {
    if (err instanceof GenError) {
      console.error(`gen-directory-plugin: ${err.message}`);
      process.exit(2);
    }
    throw err;
  }

  let stale = 0;
  for (const o of outputs) {
    const file = resolve(root, o.path);
    const want = o.bytes ?? Buffer.from(o.text, "utf8");
    const have = existsSync(file) ? readFileSync(file) : null;
    if (have && have.equals(want)) continue;
    if (check) {
      stale++;
      console.error(`${o.path} is out of date`);
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, want);
      console.log(`updated ${o.path}`);
    }
  }
  for (const path of stray(root, outputs)) {
    if (check) {
      stale++;
      console.error(`${path} is not generated; delete it`);
    } else {
      rmSync(resolve(root, path));
      console.log(`deleted ${path}`);
    }
  }
  if (!check && existsSync(resolve(root, OUT_ROOT))) pruneEmptyDirs(resolve(root, OUT_ROOT));
  const violations = directoryViolations(root);
  for (const v of violations) console.error(`directory rule: ${v}`);
  if (stale) console.error("run: node scripts/gen-directory-plugin.mjs");
  if (stale || violations.length) process.exit(1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
